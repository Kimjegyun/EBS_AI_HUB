import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'

const root = process.cwd()
const dir = await fs.mkdtemp(path.join(root, '.runtime/master-purge-test-'))
process.chdir(dir)
process.env.DATABASE_PATH = path.join(dir, 'test.db')
const { initDatabase, run, get, db } = await import('../server/src/config/database')
await initDatabase()
await run('CREATE TABLE inventory_submission_books(scope TEXT PRIMARY KEY,master_id TEXT,file_id TEXT)')
await run('CREATE TABLE inventory_submission_assets(scope TEXT,asset_key TEXT)')
await run('CREATE TABLE inventory_submission_audit(scope TEXT,asset_key TEXT)')
const { listMasterFiles, purgeMasterFile } = await import('../server/src/services/inventoryMasterFiles')
for (const folder of ['inventory-survey', 'inventory', 'inventory-photos', 'inventory-erp']) await fs.mkdir(`uploads/${folder}`, { recursive: true })
for (const id of ['target', 'keep']) {
  await run('INSERT INTO inventory_survey_forms(id,file_name,stored_name,size) VALUES (?,?,?,?)', [id, id + '.xlsx', id + '.xlsx', 4])
  await fs.writeFile(`uploads/inventory-survey/${id}.xlsx`, id)
  await run('INSERT INTO inventory_datasets(id,title,parent_dept,asset_count,assets_json,source) VALUES (?,?,?,?,?,?)', [id, id, 'HQ', 1, '[]', `survey-form:${id}|sheet:HQ`])
  await run('INSERT INTO inventory_sessions(id,name,dataset_id,parent_dept,created_by,results_json) VALUES (?,?,?,?,?,?)', [id, '2026 survey', id, 'HQ', 'test', '{"A1":{"confirmed":true}}'])
}
await run('INSERT INTO inventory_files(id,kind,file_name,stored_name,size) VALUES (?,?,?,?,?)', ['submission-target', 'dept-comparison', 'out.xlsx', 'submission-target-1.xlsx', 4])
await fs.writeFile('uploads/inventory/submission-target-1.xlsx', 'data')
await fs.writeFile('uploads/inventory/submission-target-0.xlsx', 'older')
await run('INSERT INTO inventory_submission_books VALUES (?,?,?)', ['target:2026', 'target', 'submission-target'])
await run('INSERT INTO inventory_submission_assets VALUES (?,?)', ['target:2026', 'A1'])
await run('INSERT INTO inventory_submission_audit VALUES (?,?)', ['target:2026', 'A1'])
await run('INSERT INTO inventory_photos(id,session_id,asset_no,file_name,stored_name,content_type,size) VALUES (?,?,?,?,?,?,?)', ['photo', 'target', 'A1', 'p.jpg', 'p.jpg', 'image/jpeg', 4])
await fs.writeFile('uploads/inventory-photos/p.jpg', 'photo')
const preview = (await listMasterFiles('target'))[0]
assert.equal(preview.sessionCount, 1); assert.equal(preview.photoCount, 1)
await run('UPDATE inventory_sessions SET results_json=? WHERE id=?', ['{"A1":{"confirmed":true},"A2":{}}', 'target'])
await assert.rejects(() => purgeMasterFile('target', preview.token), /변경/)
assert.equal(await fs.readFile('uploads/inventory-survey/target.xlsx', 'utf8'), 'target')
const fresh = (await listMasterFiles('target'))[0]
const result = await purgeMasterFile('target', fresh.token)
assert.equal(result.ok, true); assert.equal(result.cleanupPending, false)
assert.deepEqual(result.datasetIds, ['target'])
assert.equal(await get('SELECT * FROM inventory_sessions WHERE id=?', ['target']), undefined)
assert.equal(await get('SELECT * FROM inventory_datasets WHERE id=?', ['target']), undefined)
assert.equal(await get('SELECT * FROM inventory_submission_assets WHERE scope=?', ['target:2026']), undefined)
assert.ok(await get('SELECT * FROM inventory_sessions WHERE id=?', ['keep']))
assert.equal(await fs.readFile('uploads/inventory-survey/keep.xlsx', 'utf8'), 'keep')
await assert.rejects(() => fs.stat('uploads/inventory-survey/target.xlsx'))
await assert.rejects(() => fs.stat('uploads/inventory/submission-target-0.xlsx'))
await assert.rejects(() => fs.stat('uploads/inventory/submission-target-1.xlsx'))
await assert.rejects(() => fs.stat('uploads/inventory-photos/p.jpg'))
assert.deepEqual((await listMasterFiles()).map(file => file.id), ['keep'])
db.close()
process.chdir(root)
console.log('PASS deletion preview, stale confirmation protection, scoped DB/photo/file purge, other master preservation')
process.exit(0)
