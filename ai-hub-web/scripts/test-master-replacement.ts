import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
import * as XLSX from 'xlsx'

const root = process.cwd()
const dir = await fs.mkdtemp(path.join(root, '.runtime/master-replacement-test-'))
process.chdir(dir)
process.env.DATABASE_PATH = path.join(dir, 'test.db')
const { run, get, db } = await import('../server/src/config/database')
const { getLatestSurveyForm, deleteSurveyForm, uploadSurveyForm, resolveStoredSurveyForm } = await import('../server/src/controllers/inventory.controller')
await run('CREATE TABLE inventory_survey_forms(id TEXT PRIMARY KEY,file_name TEXT,stored_name TEXT,sheet_names TEXT,size INTEGER,uploaded_by TEXT,uploaded_at TEXT DEFAULT CURRENT_TIMESTAMP,retired_at TEXT)')
await run('CREATE TABLE inventory_datasets(id TEXT PRIMARY KEY,title TEXT,parent_dept TEXT,asset_count INTEGER,assets_json TEXT,uploaded_by TEXT,uploaded_at TEXT,source TEXT)')
await run('CREATE TABLE inventory_sessions(id TEXT PRIMARY KEY,dataset_id TEXT)')
await fs.mkdir('uploads/inventory-survey', { recursive: true })
for (const id of ['old', 'current']) {
  await run('INSERT INTO inventory_survey_forms(id,file_name,stored_name,sheet_names,size) VALUES (?,?,?,?,?)', [id, id + '.xlsx', id + '.xlsx', '["HQ"]', 1])
  await fs.writeFile(`uploads/inventory-survey/${id}.xlsx`, 'test')
}
await run('INSERT INTO inventory_datasets(id,title,parent_dept,asset_count,source) VALUES (?,?,?,?,?)', ['d1', 'HQ', 'HQ', 1, 'survey-form:current|sheet:HQ'])
await run('INSERT INTO inventory_sessions VALUES (?,?)', ['s1', 'd1'])
function response() { return { code: 200, body: null as any, status(code: number) { this.code = code; return this }, json(body: unknown) { this.body = body; return this } } }
const removed = response()
await deleteSurveyForm({ params: { id: 'current' } } as any, removed as any)
assert.equal(removed.code, 200)
assert.equal(removed.body.archived, true)
assert.ok(await resolveStoredSurveyForm('current'))
assert.ok(await get('SELECT * FROM inventory_sessions WHERE id=?', ['s1']))
const empty = response()
await getLatestSurveyForm({} as any, empty as any)
assert.equal(empty.body, null, 'An older master must not reappear after removal')
const sheet = XLSX.utils.aoa_to_sheet([[], [], [], [], [], [], [], ['자산번호', '자산명', '설치부서'], ['A1', 'Test asset', 'Dept']])
const workbook = XLSX.utils.book_new()
XLSX.utils.book_append_sheet(workbook, sheet, 'HQ')
const uploaded = response()
await uploadSurveyForm({ user: { id: 'admin' }, file: { buffer: XLSX.write(workbook, { type: 'buffer', bookType: 'xlsx' }), originalname: 'new.xlsx', size: 100 } } as any, uploaded as any)
assert.equal(uploaded.code, 200)
assert.equal(uploaded.body.datasetsCreated, 1)
const active = response()
await getLatestSurveyForm({} as any, active as any)
assert.equal(active.body.fileName, 'new.xlsx')
assert.notEqual(active.body.id, 'current')
const invalidBook = XLSX.utils.book_new()
XLSX.utils.book_append_sheet(invalidBook, XLSX.utils.aoa_to_sheet([['No assets']]), 'HQ')
const invalid = response()
await uploadSurveyForm({ user: { id: 'admin' }, file: { buffer: XLSX.write(invalidBook, { type: 'buffer', bookType: 'xlsx' }), originalname: 'empty.xlsx', size: 10 } } as any, invalid as any)
assert.equal(invalid.code, 400)
const stillActive = response()
await getLatestSurveyForm({} as any, stillActive as any)
assert.equal(stillActive.body.id, active.body.id)
assert.equal((await get('SELECT source FROM inventory_datasets WHERE id=?', ['d1'])).source, 'survey-form:current|sheet:HQ')
db.close()
process.chdir(root)
console.log('PASS retire in-use master, preserve records/source, no older version resurrection, upload new master and dataset')
process.exit(0)
